// ─── Progress bar ──────────────────────────────────────────────────────────────
function bar(done, total, errors) {
  const pct = Math.round((done / total) * 100);
  const filled = Math.round((done / total) * 30);
  const b = '█'.repeat(filled) + '░'.repeat(30 - filled);
  process.stdout.write(`\r[${b}] ${pct}% — ${done}/${total}, ${errors} errors`);
}

