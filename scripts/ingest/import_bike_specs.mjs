// ─── Year expansion ────────────────────────────────────────────────────────────
// years <= 26 → 20xx, 27–99 → 19xx
function cy(y) { return y <= 26 ? 2000 + y : 1900 + y; }

function expandYears(raw) {
  const years = new Set();
  for (const seg of String(raw).split(',').map(s => s.trim())) {
    if (seg.includes('-')) {
      const [a, b] = seg.split('-').map(s => parseInt(s.trim()));
      const start = cy(a), end = cy(b);
      for (let y = start; y <= end; y++) years.add(y);
    } else {
      years.add(cy(parseInt(seg)));
    }
  }
  return [...years].sort((a, b) => a - b);
}

